#!/usr/bin/env bash
#
# install.sh - one-time (idempotent) setup on a server. Run as root from a checkout of this repo:
#
#     sudo ADMIN_EMAIL=ops@example.com SMTP_URL=smtps://... SMTP_USER=... SMTP_PASS=... ./install.sh
#
# Optional env: PATCH_ONCALENDAR ("Fri *-*-* 22:00:00", server local time),
#               PATCH_JITTER_MIN (random start delay, default 60), REPO_REF, GITHUB_TOKEN, PATCH_SCOPE ...
# Re-run it after changing the agent script or the schedule.
#
set -euo pipefail
[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE=/opt/os-patch
CONF_DIR=/etc/os-patch
CONF="$CONF_DIR/patch.conf"
PATCH_ONCALENDAR="${PATCH_ONCALENDAR:-Fri *-*-* 22:00:00}"
PATCH_JITTER_MIN="${PATCH_JITTER_MIN:-60}"

# 1. dependencies (only what is missing; avoids curl/curl-minimal conflicts on Amazon Linux 2023)
need=()
for c in git curl; do command -v "$c" >/dev/null 2>&1 || need+=("$c"); done
if [ ${#need[@]} -gt 0 ]; then
  if   command -v apt-get >/dev/null 2>&1; then apt-get update -q && DEBIAN_FRONTEND=noninteractive apt-get install -y -q "${need[@]}" ca-certificates
  elif command -v dnf     >/dev/null 2>&1; then dnf install -y -q "${need[@]}"
  elif command -v yum     >/dev/null 2>&1; then yum install -y -q "${need[@]}"
  else echo "install ${need[*]} manually" >&2; exit 1; fi
fi

# 2. files
mkdir -p "$BASE/bin" "$CONF_DIR" /var/lib/os-patch /var/log/os-patch
chmod 700 "$CONF_DIR" /var/lib/os-patch /var/log/os-patch
if [ "$SRC" != "$BASE/repo" ]; then rm -rf "$BASE/repo"; cp -a "$SRC" "$BASE/repo"; fi
[ -d "$BASE/repo/.git" ] || echo "WARNING: no .git directory - the agent cannot pull updates from GitHub" >&2
install -m 0755 "$BASE/repo/patch-agent.sh" "$BASE/bin/patch-agent.sh"
chmod 0755 "$BASE/repo/patch.sh"

# 3. config (never overwritten if it already exists)
if [ ! -f "$CONF" ]; then
  : "${REPO_REF:=main}" "${ADMIN_EMAIL:=}" "${MAIL_FROM:=}" "${MAIL_METHOD:=smtp}" "${SMTP_URL:=}"
  : "${SMTP_USER:=}" "${SMTP_PASS:=}" "${GITHUB_TOKEN:=}" "${DEPLOY_KEY:=}" "${PATCH_SCOPE:=all}"
  : "${REBOOT_DELAY_MIN:=1}" "${REBOOT_ON_FAILURE:=true}" "${MIN_INTERVAL_DAYS:=6}"
  umask 077
  {
    echo "# Generated by install.sh - see patching.conf.example for documentation"
    for v in REPO_REF GITHUB_TOKEN DEPLOY_KEY ADMIN_EMAIL MAIL_FROM MAIL_METHOD SMTP_URL SMTP_USER SMTP_PASS \
             PATCH_SCOPE REBOOT_DELAY_MIN REBOOT_ON_FAILURE MIN_INTERVAL_DAYS; do
      printf '%s=%q\n' "$v" "${!v}"
    done
  } > "$CONF"
  chmod 600 "$CONF"
  echo "wrote $CONF"
else
  echo "kept existing $CONF"
fi

# 4. systemd units
cat > /etc/systemd/system/os-patch.service <<'EOF'
[Unit]
Description=Weekly OS patching (pull latest from GitHub, patch, report, reboot)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/opt/os-patch/bin/patch-agent.sh
TimeoutStartSec=4h
Nice=10
EOF

cat > /etc/systemd/system/os-patch.timer <<EOF
[Unit]
Description=Weekly OS patching timer (every Friday)

[Timer]
OnCalendar=${PATCH_ONCALENDAR}
RandomizedDelaySec=$(( PATCH_JITTER_MIN * 60 ))
AccuracySec=1min
Persistent=true

[Install]
WantedBy=timers.target
EOF

cat > /etc/systemd/system/os-patch-postboot.service <<'EOF'
[Unit]
Description=OS patching post-reboot verification and report
After=network-online.target multi-user.target
Wants=network-online.target
ConditionPathExists=/var/lib/os-patch/reboot_pending

[Service]
Type=oneshot
ExecStartPre=/bin/sleep 90
ExecStart=/opt/os-patch/bin/patch-agent.sh --post-reboot
TimeoutStartSec=15min

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable --now os-patch.timer
systemctl enable os-patch-postboot.service

echo
echo "Installed. Schedule: ${PATCH_ONCALENDAR} (+ up to ${PATCH_JITTER_MIN} min jitter), server local time."
systemctl list-timers os-patch.timer --no-pager || true
echo "Test without changing anything:  sudo $BASE/bin/patch-agent.sh --force --dry-run"
